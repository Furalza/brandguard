"""Tests for icon similarity.

Fixtures are generated by scripts/make_test_icons.py. The tests validate the
perceptual-hash behaviour, including its known colour-insensitivity limit.
"""

import subprocess
import sys
from pathlib import Path

import pytest

from brandguard.triage.icon_similarity import compare_icons, icon_signal
from brandguard.triage.signals import Direction

ICONS = Path(__file__).resolve().parents[1] / "data" / "mock_icons"


@pytest.fixture(scope="module", autouse=True)
def _ensure_icons():
    if not (ICONS / "official.png").exists():
        subprocess.run(
            [sys.executable, "scripts/make_test_icons.py"],
            cwd=ICONS.parents[1],
            check=True,
        )


def _p(name: str) -> str:
    return str(ICONS / f"{name}.png")


def test_identical_layout_is_near_zero_distance():
    assert compare_icons(_p("near_copy"), _p("official")).distance <= 6


def test_unrelated_icon_is_far():
    assert compare_icons(_p("unrelated"), _p("official")).distance > 20


def test_copy_produces_suspicious_signal():
    s = icon_signal(_p("near_copy"), _p("official"))
    assert s is not None and s.direction == Direction.SUSPICIOUS


def test_unrelated_produces_legitimate_signal():
    s = icon_signal(_p("unrelated"), _p("official"))
    assert s is not None and s.direction == Direction.LEGITIMATE


def test_recolour_limit_is_documented_behaviour():
    # Known limit: pHash is colour-insensitive, so a same-layout recolour still
    # reads as similar. This test documents the behaviour rather than asserting
    # an ideal we do not achieve.
    assert compare_icons(_p("recolour"), _p("official")).distance <= 12


def test_missing_icon_abstains():
    assert icon_signal(None, _p("official")) is None
    assert icon_signal(_p("official"), None) is None
